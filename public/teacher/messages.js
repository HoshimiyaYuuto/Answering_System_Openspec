// 狀態中保存的訊息可以是字串（原樣顯示）、{ key, params }（前端訊息）、
// { code, fallback }（伺服器錯誤，fallback 為原文），或 { parts: [...] } 依序串接（design 第 2 節）
export function renderMessage(t, value) {
  if (value === null || value === undefined) return '';
  if (typeof value !== 'object') return String(value);
  if (Array.isArray(value.parts)) return value.parts.map((part) => renderMessage(t, part)).join('');
  if (value.key) {
    const params = {};
    for (const [name, param] of Object.entries(value.params ?? {})) {
      params[name] = typeof param === 'object' && param !== null ? renderMessage(t, param) : param;
    }
    return t(value.key, params);
  }
  if ('code' in value || 'fallback' in value) return translateError(t, value.code, value.fallback);
  return '';
}

